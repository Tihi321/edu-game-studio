const TABLES: Record<string, Partial<Record<UiKey, string>>> = { hr: HR, de: DE }

export type Ui = (key: UiKey, vars?: Record<string, string | number>) => string

/** The `ui` function of an edition: the course catalog's `ui.<key>` first, then the language table, then English. */
export function makeUi(lang: string, catalog?: Pick<TextCatalog, 'strings'>): Ui {
  const table = TABLES[lang] ?? TABLES[lang.split('-')[0] ?? ''] ?? {}
  return (key, vars) => {
    let s: string = catalog?.strings[`ui.${key}`] ?? table[key] ?? EN[key]
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v))
    return s
  }
}

